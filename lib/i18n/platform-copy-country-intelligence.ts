export const COUNTRY_INTELLIGENCE_COPY_LOCALES = ["en", "uz", "ru", "tr"] as const;

const BY_LOCALE: Record<(typeof COUNTRY_INTELLIGENCE_COPY_LOCALES)[number], CountryIntelligenceCopy> = {
  en: EN,
  uz: UZ,
  ru: RU,
  tr: TR,
};

export function getCountryIntelligenceCopy(locale: string): CountryIntelligenceCopy {
  const key = (locale || "en").toLowerCase().slice(0, 2) as (typeof COUNTRY_INTELLIGENCE_COPY_LOCALES)[number];
  return BY_LOCALE[key] ?? EN;
}

export function fillCountryCopy(template: string, vars: Record<string, string>): string {
  return Object.entries(vars).reduce((acc, [k, v]) => acc.replaceAll(`{${k}}`, v), template);
}
