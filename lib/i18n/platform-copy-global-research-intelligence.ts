export const GRI_COPY_LOCALES = ["en", "uz", "ru", "tr"] as const;

const BY: Record<(typeof GRI_COPY_LOCALES)[number], GriCopy> = { en: EN, uz: UZ, ru: RU, tr: TR };

export function getGriCopy(locale: string): GriCopy {
  const key = (locale || "en").toLowerCase().slice(0, 2) as (typeof GRI_COPY_LOCALES)[number];
  return BY[key] ?? EN;
}
