export const SDN_COPY_LOCALES = ["en", "uz", "ru", "tr"] as const;
const BY: Record<(typeof SDN_COPY_LOCALES)[number], SdnCopy> = { en: EN, uz: UZ, ru: RU, tr: TR };

export function getSdnCopy(locale: string): SdnCopy {
  const key = (locale || "en").toLowerCase().slice(0, 2) as (typeof SDN_COPY_LOCALES)[number];
  return BY[key] ?? EN;
}
