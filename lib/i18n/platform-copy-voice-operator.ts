export function voiceOperatorCopyForLanguage(lang: string): VoiceOperatorCopy {
  if (lang === "uz") return VOICE_OPERATOR_UZ;
  if (lang === "ru") return VOICE_OPERATOR_RU;
  if (lang === "tr") return VOICE_OPERATOR_TR;
  return VOICE_OPERATOR_EN;
}

